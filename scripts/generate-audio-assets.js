#!/usr/bin/env node
// Run from project root: node scripts/generate-audio-assets.js
// Regenerate if audio files are added or renamed.

const fs = require("fs");
const path = require("path");

const audioDir = path.join(__dirname, "../assets/audio");
const outFile = path.join(__dirname, "../constants/audioAssets.ts");

const entries = [];

for (let ch = 1; ch <= 18; ch++) {
  const chDir = path.join(audioDir, `Chapter_${ch}`);
  if (!fs.existsSync(chDir)) continue;
  const files = fs.readdirSync(chDir).filter(f => f.toUpperCase().endsWith(".MP3"));
  for (const file of files) {
    const key = file.replace(/\.MP3$/i, "");
    entries.push(`  "${key}": require("../assets/audio/Chapter_${ch}/${file}"),`);
  }
}

const content = `// AUTO-GENERATED by scripts/generate-audio-assets.js — do not edit manually
// Maps "chapter-verse" → bundled MP3 require handle for expo-av

const AUDIO_ASSETS: Record<string, number> = {
${entries.join("\n")}
};

export default AUDIO_ASSETS;
`;

fs.writeFileSync(outFile, content, "utf8");
console.log(`Written ${entries.length} entries to constants/audioAssets.ts`);
